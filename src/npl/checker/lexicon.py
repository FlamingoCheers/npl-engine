"""情绪词表与确定性扫描（规则引擎的离线兜底层）。

NAR-051 的第一道检测不依赖 LLM：直接命名情绪的文本可被词表命中。
（restrained_literary 等风格声明"禁止直接命名情绪"时才视为违规。）
"""

EMOTION_WORDS = [
    "不安", "紧张", "焦虑", "担忧", "担心", "害怕", "恐惧", "惊恐", "惶恐",
    "慌乱", "心慌", "慌张", "惊慌",
    "愤怒", "恼怒", "愤恨", "怨恨", "愤慨", "恼火", "烦躁",
    "悲伤", "悲痛", "哀伤", "悲哀", "伤心", "伤感", "悲怆",
    "沮丧", "失落", "绝望", "无助", "无奈", "委屈",
    "愧疚", "内疚", "自责", "悔恨", "懊悔", "懊恼", "羞愧", "惭愧", "尴尬",
    "厌恶", "反感", "恶心", "轻蔑", "不屑", "鄙夷",
    "嫉妒", "妒忌", "羡慕", "眼红",
    "孤独", "寂寞", "空虚", "凄凉", "苍凉", "酸楚", "苦涩", "心酸",
    "喜悦", "高兴", "快乐", "欢喜", "欣喜", "欣慰", "狂喜", "惊喜",
    "惊讶", "诧异", "震惊", "吃惊", "愕然",
    "痛苦", "折磨", "煎熬", "挣扎",
    "释然", "坦然", "忐忑", "犹疑", "踌躇",
]


def scan_emotions(prose):
    """返回 [{subject: '?', emotion: word, span: 含词句子}]。词表命中即报。"""
    hits = []
    for line in prose.splitlines():
        for word in EMOTION_WORDS:
            start = 0
            while True:
                i = line.find(word, start)
                if i < 0:
                    break
                hits.append({"subject": "?", "emotion": word,
                             "span": line.strip()[:80]})
                start = i + len(word)
    return hits
